// Rebuild the homepage-only palette from the existing section rules.
// Only color-bearing declarations are copied; geometry and behavior stay in the originals.
const fs = require('fs');
const postcss = require('postcss');
const sources = ['styles.css', 'app/globals.css', 'app/hero-refresh.css', 'components/AcademyMap.css', 'components/CourseCardFacts.css'];
const isColorProperty = /^(?:--[\w-]+|color|background(?:-color|-image)?|border(?:-\w+)?|outline(?:-color)?|box-shadow|text-shadow|fill|stroke|caret-color|accent-color|text-decoration-color|filter)$/i;
const colorPattern = /rgba?\(\s*(\d{1,3})\s*,\s*(\d{1,3})\s*,\s*(\d{1,3})(?:\s*,\s*([\d.]+%?))?\s*\)|#([\da-f]{8}|[\da-f]{6}|[\da-f]{4}|[\da-f]{3})\b/gi;
function palette(r,g,b) {
  const max=Math.max(r,g,b), min=Math.min(r,g,b), l=(max+min)/2/255, saturation=max ? (max-min)/max : 0;
  if (max === min) return [r,g,b];
  // Very pale tinted surfaces become a quiet mint-white, not another dark color.
  if (l > .91) return l > .97 ? [250,253,252] : [237,247,245];
  if (l > .79 && saturation > .075) return [213,237,233];
  if (saturation < .075) return [r,g,b];
  const warm = r > g*1.12 && r > b*1.14 && saturation > .35;
  if (warm) return l < .30 ? [137,108,26] : [212,175,55];
  if (l < .19) return [10,46,46];
  if (l < .36) return [27,94,94];
  if (l < .53) return [43,122,122];
  if (l < .70) return [58,155,155];
  return [76,181,181];
}
function mapColors(value) {
  return value.replace(colorPattern, (match,r,g,b,alpha,hex) => {
    if (hex) {
      let h=hex; if(h.length===3||h.length===4) h=[...h].map(x=>x+x).join('');
      const rgb=[0,2,4].map(i=>parseInt(h.slice(i,i+2),16));
      const mapped=palette(...rgb).map(n=>n.toString(16).padStart(2,'0')).join('');
      return '#'+mapped+(h.length===8?h.slice(6):'');
    }
    const rgb=palette(+r,+g,+b);
    return alpha === undefined ? `rgb(${rgb.join(', ')})` : `rgba(${rgb.join(', ')}, ${alpha})`;
  });
}
const result=postcss.root();
for (const file of sources) {
  const tree=postcss.parse(fs.readFileSync(file,'utf8'),{from:file});
  tree.walkAtRules(at=>{if (/keyframes$/i.test(at.name)) at.remove();});
  tree.walkRules(rule=>{
    const selectors=postcss.list.comma(rule.selector).map(selector=>selector.trim()).filter(s=>s && !/^:root\b/.test(s));
    if (!selectors.length) { rule.remove(); return; }
    rule.selector=selectors.map(s=>{
      if (/^\.landing-page\b/.test(s)) return s;
      if (/^(?:html\s+)?body\b/.test(s)) return s.replace(/^(?:html\s+)?body\b/, '.landing-page');
      if (/^html\b/.test(s)) return s.replace(/^html\b/, '.landing-page');
      return ':where(.landing-page) '+s;
    }).join(', ');
    rule.walkDecls(decl=>{
      if (!isColorProperty.test(decl.prop) || !colorPattern.test(decl.value)) { colorPattern.lastIndex=0; decl.remove(); return; }
      colorPattern.lastIndex=0;
      // Preserve image URLs and change only the accompanying overlay colors.
      const urls=[];
      const protectedValue=decl.value.replace(/url\((?:[^)(]|\([^)]*\))*\)/gi, url => `__HOME_IMAGE_${urls.push(url)-1}__`);
      decl.value=mapColors(protectedValue).replace(/__HOME_IMAGE_(\d+)__/g, (_, i) => urls[+i]);
      // Shorthand resets can change layout or background positioning. Copy only
      // the color/image part of those declarations into the scoped palette.
      if (decl.prop === 'background') {
        decl.prop = /(?:gradient|url)\(/i.test(decl.value) ? 'background-image' : 'background-color';
      } else if (/^border(?:-(?:top|right|bottom|left))?$/.test(decl.prop)) {
        const color=decl.value.match(/(?:rgba?\([^)]*\)|#[\da-f]{3,8}\b)/i);
        if (!color) { decl.remove(); return; }
        decl.prop += '-color';
        decl.value = color[0];
      } else if (decl.prop === 'outline') {
        const color=decl.value.match(/(?:rgba?\([^)]*\)|#[\da-f]{3,8}\b)/i);
        if (!color) { decl.remove(); return; }
        decl.prop = 'outline-color';
        decl.value = color[0];
      }
    });
    if (!rule.nodes?.length) rule.remove();
  });
  tree.walkAtRules(at=>{ if (!at.nodes?.length || !['media','supports','container','layer'].includes(at.name)) at.remove(); });
  tree.walkComments(c=>c.remove());
  result.append(...tree.nodes);
}
fs.writeFileSync('app/home-palette-generated.css','/* Generated by scripts/build-home-palette.cjs. Color declarations only. */\n'+result.toString()+'\n');
